// Generates js/data/countries.js and copies flag SVGs from the flag-icons package.
// Usage: npm i --no-save flag-icons world-countries && node scripts/build-data.mjs
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const countries = require('world-countries');
const flagDir = path.join(path.dirname(require.resolve('flag-icons/package.json')), 'flags', '4x3');

const EXTRA_MAIN = new Set(['VA', 'PS', 'XK', 'TW']); // non-UN but commonly counted
const continentOf = (c) => {
  if (c.region === 'Americas') return c.subregion === 'South America' ? 'South America' : 'North America';
  if (c.region === 'Antarctic') return 'Antarctica';
  return c.region; // Africa, Asia, Europe, Oceania
};

const out = [];
for (const c of countries) {
  const code = c.cca2.toLowerCase();
  const svg = path.join(flagDir, `${code}.svg`);
  if (!fs.existsSync(svg)) continue;
  fs.copyFileSync(svg, path.join(root, 'flags', `${code}.svg`));
  const alt = new Set([c.name.official, ...(c.altSpellings || [])]);
  alt.delete(c.name.common);
  out.push({
    code,
    name: c.name.common,
    alt: [...alt].filter((s) => s.length > 3),
    capital: (c.capital || [])[0] || '',
    continent: continentOf(c),
    sub: c.subregion || '',
    main: c.unMember || EXTRA_MAIN.has(c.cca2),
    area: c.area,
  });
}
// Regional flags shipped by flag-icons (used in the Regions & Cities mode)
for (const code of ['gb-eng', 'gb-sct', 'gb-wls', 'gb-nir', 'es-ct', 'es-pv', 'es-ga', 'eu', 'un']) {
  fs.copyFileSync(path.join(flagDir, `${code}.svg`), path.join(root, 'flags', `${code}.svg`));
}
out.sort((a, b) => a.name.localeCompare(b.name));
fs.writeFileSync(
  path.join(root, 'js', 'data', 'countries.js'),
  '// Generated by scripts/build-data.mjs — do not edit by hand.\nwindow.COUNTRIES = ' + JSON.stringify(out) + ';\n'
);
console.log(`${out.length} countries, ${out.filter((c) => c.main).length} main`);
